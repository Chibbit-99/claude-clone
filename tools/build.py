#!/usr/bin/env python3
"""Build app/new (the reconstructed new-chat page) from the SingleFile clones.

Nothing in this file re-authors markup or CSS: every byte of UI comes from
/clones (which is generated by CI from /extractions). The build only

  * copies the original stylesheets / fonts / favicon,
  * strips SingleFile's captured <script> payloads,
  * slices the popovers, dialogs and inline panels out of the state captures
    and stores them verbatim in <template> elements,
  * appends app.js which wires the interactions together.

Run: python3 tools/build.py
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clonehtml as C  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "new"
SRC = C.CLONES / "index"

# popover / dialog fragments: name -> (extraction, portal index)
PORTALS = {
    "pop-add": ("add", 0),
    "pop-add-project": ("addaddtoproject", 1),
    "pop-add-connectors": ("addconnectors", 1),
    "pop-add-design-system": ("adddesignsystem", 1),
    "pop-add-skills": ("addskills", 1),
    "pop-model": ("modelselect", 0),
    "pop-model-effort": ("modelselecteffort", 1),
    "pop-model-more": ("modelselectmore", 1),
    "dialog-cowork": ("cowork", 0),
    "dialog-upload": ("upload", 0),
    "dialog-newproject": ("newproject", 0),
}

STYLESHEETS = ("stylesheet_0.css", "stylesheet_1.css", "stylesheet_2.css")


def portals(name: str) -> list[str]:
    """Split #portal-root of an extraction into its data-base-ui-portal subtrees."""
    content, _ = C.portal(name)
    found = []
    for start, a, _self in C.find_tags(content, "div"):
        if "data-base-ui-portal" in a:
            found.append(C.outer(content, start))
    if not found:
        raise SystemExit(f"{name}: no data-base-ui-portal found")
    return found


def inline_panel(name: str, marker: str) -> str:
    """Slice an absolutely positioned inline panel (suggestions popover)."""
    html = C.page(name)
    start = html.find(marker)
    if start == -1:
        raise SystemExit(f"{name}: marker {marker!r} missing")
    start = html.rfind("<div", 0, start)
    return C.outer(html, start)


def project_chip() -> str:
    """The little project chip that appears in the composer once a project is picked."""
    html = C.page("workinginproject")
    for start, a, _ in C.find_tags(html, "div"):
        if a.get("class", "").strip() == "shrink-0 flex":
            return C.outer(html, start)
    raise SystemExit("workinginproject: project chip not found")


def strip_scripts(html: str) -> str:
    html = re.sub(r"<script\b[^>]*>.*?</script>", "", html, flags=re.S)
    html = re.sub(r"<script\b[^>]*/?>", "", html)
    html = re.sub(r"<!--\s*Page saved with SingleFile.*?-->", "", html, flags=re.S)
    return html


def template(name: str, payload: str) -> str:
    return f'<template data-frag="{name}">{payload}</template>'


def main() -> None:
    html = strip_scripts(C.page("index"))

    # the saved page keeps its stylesheets inside <body>; leaving them there
    # preserves the original cascade order exactly, so only the paths matter.
    for css in STYLESHEETS:
        assert f'href={css}' in html or f'href="{css}"' in html, f"missing link for {css}"

    frags = []
    for name, (source, idx) in PORTALS.items():
        parts = portals(source)
        if idx >= len(parts):
            raise SystemExit(f"{source}: expected portal #{idx}, only {len(parts)} found")
        frags.append((name, parts[idx]))

    frags.append(("panel-suggestions", inline_panel("suggestions", 'class="absolute top-4 inset-x-3.5 z-10')))
    frags.append(("project-chip", project_chip()))

    block = "".join(template(n, p) for n, p in frags)
    script = '<script src="app.js" defer></script>'
    if "</body>" in html:
        html = html.replace("</body>", block + script + "</body>")
    else:
        # SingleFile drops the trailing </body></html>; templates go at the end.
        html = html + block + script + "</body></html>"

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "index.html").write_text(html)

    for css in STYLESHEETS:
        shutil.copyfile(SRC / css, OUT / css)

    # assets: the base page plus every extraction a fragment came from
    sources = [SRC] + [C.CLONES / src for src, _ in PORTALS.values()]
    for sub in ("fonts", "images"):
        target = OUT / sub
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True)
        for source in sources:
            folder = source / sub
            if not folder.is_dir():
                continue
            for asset in sorted(folder.iterdir()):
                if asset.is_file() and not (target / asset.name).exists():
                    shutil.copyfile(asset, target / asset.name)

    sizes = {n: len(p) for n, p in frags}
    print("wrote", (OUT / "index.html").relative_to(ROOT), f"{len(html):,} bytes")
    print("fragments:", ", ".join(f"{n}({s:,})" for n, s in sizes.items()))


if __name__ == "__main__":
    main()
